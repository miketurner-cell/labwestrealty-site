// ============================================================================
// sold-data — serve the sold-listing JSON files to signed-in users only
// (site review, Mike 2026-09-29 item 3; NLAR VOW Policy 1.0/5.0/13.0/27.0).
// ============================================================================
// Before: /listings/sold/data.json, /listings/sold/<town>/data.json and
// /listings/sold/detail/<shard>.json were static files anyone could download
// (Gander 12,793 rows, Avalon 8,533, Goose Bay 158). _redirects now forces those
// paths here (200!, so the page URL is unchanged). The files stay in the repo and
// in the deploy (bundled into this function via netlify.toml included_files);
// only the public URL changes behaviour.
//
//   * No / bad token  -> 401 {"error":"sign_in_required", ..., "rows": []}
//     A clear sign-in answer, never a 404, and an empty "rows" so a page that
//     reads payload.rows degrades to "no data" instead of throwing.
//   * Valid token     -> the file, Cache-Control: private, no-store.
//   * Rate limit      -> 429 after RATE_MAX file reads per user per 10 minutes
//     (per function instance; a real per-user counter lands with the audit table).
//
// Token check: GoTrue GET /auth/v1/user with the site's PUBLISHABLE key (the same
// public key js/auth.js ships), so no secret is needed on any of the 3 sites.
// Server-side readers (generator, emitters, fb-post, alerts on the runner/box)
// read the files from the repo on disk and are unaffected.
// ============================================================================

import type { Handler, HandlerEvent } from '@netlify/functions';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const SUPABASE_URL = (process.env.SUPABASE_URL || 'https://mpzuxamyhzqsrsuelvlq.supabase.co').replace(/\/+$/, '');
// Public, browser-shipped publishable key (identical to js/auth.js). Not a secret.
const PUBLISHABLE_KEY = process.env.SUPABASE_PUBLISHABLE_KEY || 'sb_publishable_NReIINWVCZnIQpVoq9uu4w_OXoBPlaL';
export const RATE_MAX = Number(process.env.SOLD_DATA_RATE_MAX || 120);
const RATE_WINDOW_MS = 10 * 60 * 1000;

const TOWN_RE = /^[a-z0-9][a-z0-9-]{0,60}$/;
const SHARD_RE = /^[a-z0-9][a-z0-9_-]{0,60}\.json$/;

// Netlify rewrites to a function do not forward the rule's query string, so the
// original request path (event.path / rawUrl) is the primary input; the query form
// is kept for direct calls and tests.
export function resolvePath(p: string): string | null {
  const path = String(p || '').split('?')[0].replace(/\/+$/, '');
  let m;
  if (path === '/listings/sold/data.json') return 'listings/sold/data.json';
  if ((m = path.match(/^\/listings\/sold\/detail\/([^/]+)$/)) && SHARD_RE.test(m[1])) return `listings/sold/detail/${m[1]}`;
  if ((m = path.match(/^\/listings\/sold\/([^/]+)\/data\.json$/)) && TOWN_RE.test(m[1]) && m[1] !== 'detail') return `listings/sold/${m[1]}/data.json`;
  if ((m = path.match(/^\/agent-sales\/([a-z0-9-]{1,60})\.json$/))) return `agent-sales/${m[1]}.json`;
  return null;
}

export function resolveFile(q: Record<string, string | undefined>): string | null {
  if (q.f === 'data.json') return 'listings/sold/data.json';
  if (q.agent && /^[a-z0-9-]{1,60}$/.test(q.agent)) return `agent-sales/${q.agent}.json`;
  if (q.town && TOWN_RE.test(q.town)) return `listings/sold/${q.town}/data.json`;
  if (q.shard && SHARD_RE.test(q.shard)) return `listings/sold/detail/${q.shard}`;
  return null;
}

function readBundled(rel: string): string | null {
  const roots = [process.cwd(), '/var/task', join(__dirname, '..', '..'), join(__dirname, '..', '..', '..'), __dirname];
  for (const r of roots) {
    const p = join(r, rel);
    if (existsSync(p)) return readFileSync(p, 'utf8');
  }
  return null;
}

// Agent sales sidecars (agent-sales/<agent>.json) are regenerated by hand and hold sold
// cards back to 2024-05 (2026-09-29): apply the 730-day VOW window at serve time.
export function windowAgentSales(body: string, now = new Date()): string {
  try {
    const d = JSON.parse(body);
    if (!Array.isArray(d.cards)) return body;
    const cutoff = new Date(now.getTime() - 730 * 86400000).toISOString().slice(0, 10);
    d.cards = d.cards.filter((c: { sold_date?: string }) => String(c.sold_date || '') >= cutoff);
    d.card_count = d.cards.length;
    return JSON.stringify(d);
  } catch { return body; }
}

const hits = new Map<string, number[]>();
export function rateOk(userId: string, now = Date.now(), max = RATE_MAX): boolean {
  const arr = (hits.get(userId) || []).filter((t) => now - t < RATE_WINDOW_MS);
  if (arr.length >= max) { hits.set(userId, arr); return false; }
  arr.push(now); hits.set(userId, arr);
  return true;
}

async function verify(token: string): Promise<{ id: string; email: string } | null> {
  if (!token) return null;
  try {
    const r = await fetch(`${SUPABASE_URL}/auth/v1/user`, { headers: { apikey: PUBLISHABLE_KEY, Authorization: `Bearer ${token}` } });
    if (!r.ok) return null;
    const d = await r.json() as { id?: string; email?: string };
    return d.id ? { id: d.id, email: d.email || '' } : null;
  } catch {
    return null;
  }
}

// ── Signed-out single listing (Mike, 2026-10-05) ────────────────────────────
// Since item 3 (09-29) a signed-out visitor on /listings/sold/detail.html?mls=X
// got "Could not load listing data": the page's only data source answered 401.
// Social "just sold" posts link to exactly that page. Mike: "show the ungated
// facts and the sign-in prompt." So a signed-out request for a detail shard (or,
// on Goose Bay, the hub data.json its detail page reads) that names ONE MLS® number
// gets that one row and nothing else. The bulk files stay sign-in only (item 3).
//   * No sold price: the shards and data.json never carry close_price (stripped at
//     emit time; the price arrives only via RLS-gated viewpoint_prices). Any
//     price-like key is dropped here too, in case an emitter ever adds one.
//   * Rate limit: ANON_MAX single-listing reads per IP per 10 minutes.
//   * If Mike ever turns on VOW_SOLD_GATE (PR #504, "all sold data behind
//     registration", held for his GO), this path closes and the page shows the
//     sign-in prompt only.
export const ANON_MAX = Number(process.env.SOLD_DATA_ANON_MAX || 60);
const MLS_RE = /^[0-9]{6,9}$/;
const PRICE_KEY_RE = /close|sold_price|sale_price|sa_ratio|sale_to_list|sp_lp|price_per_sqft_sold/i;

export function anonSingleRow(rel: string, mls: string, body: string): string | null {
  if (!MLS_RE.test(mls)) return null;
  const isShard = rel === `listings/sold/detail/${mls.slice(0, 4)}.json`;
  if (!isShard && rel !== 'listings/sold/data.json') return null;
  try {
    const d = JSON.parse(body) as { rows?: Array<Record<string, unknown>> };
    const row = (d.rows || []).find((r) => String(r && r.mls) === mls);
    if (!row) return JSON.stringify({ rows: [], single: true });
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(row)) if (!PRICE_KEY_RE.test(k)) out[k] = row[k];
    return JSON.stringify({ rows: [out], single: true, signed_in: false });
  } catch {
    return null;
  }
}

export function requestedMls(rawUrl: string | undefined, q: Record<string, string | undefined>): string {
  try { if (rawUrl) { const v = new URL(rawUrl).searchParams.get('mls'); if (v) return v.trim(); } } catch { /* fall through */ }
  return String(q.mls || '').trim();
}

function clientIpOf(event: HandlerEvent): string {
  const h = event.headers || {};
  return String(h['x-nf-client-connection-ip'] || h['client-ip'] || String(h['x-forwarded-for'] || '').split(',')[0] || 'unknown').trim();
}

function reply(statusCode: number, body: string, extra: Record<string, string> = {}) {
  return { statusCode, body, headers: { 'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'private, no-store', Vary: 'Authorization', 'X-Robots-Tag': 'noindex', ...extra } };
}

export const handler: Handler = async (event: HandlerEvent) => {
  // Lab West (sites, D-1012-34): dark until the sold data exists. The files are written only by the gated rebuild
  // (LABWEST_LISTINGS preview or on), so while the switch is off this function answers like a missing page for everyone,
  // signed in or not. tools/tests/labwest-sold-data-test.mjs pins it.
  if (readBundled('listings/sold/data.json') == null) return reply(404, JSON.stringify({ error: 'not_found', rows: [] }));
  const q = (event.queryStringParameters || {}) as Record<string, string | undefined>;
  let origPath = event.path || '';
  try { if (event.rawUrl) origPath = new URL(event.rawUrl).pathname; } catch { /* keep event.path */ }
  const rel = resolvePath(origPath) || resolveFile(q);
  if (!rel) return reply(404, JSON.stringify({ error: 'not_found', rows: [] }));
  const bearer = String(event.headers.authorization || event.headers.Authorization || '').replace(/^Bearer\s+/i, '').trim();
  const who = await verify(bearer);
  if (!who) {
    const mls = requestedMls(event.rawUrl, q);
    if (mls && String(process.env.VOW_SOLD_GATE || 'off').toLowerCase() !== 'on') {
      const raw = readBundled(rel);
      const one = raw == null ? null : anonSingleRow(rel, mls, raw);
      if (one) {
        if (!rateOk(`ip:${clientIpOf(event)}`, Date.now(), ANON_MAX)) {
          return reply(429, JSON.stringify({ error: 'rate_limited', rows: [] }), { 'Retry-After': '600' });
        }
        return reply(200, one);
      }
    }
    return reply(401, JSON.stringify({
      error: 'sign_in_required',
      message: 'Sold listings are available to registered users. Please sign in to see them.',
      sign_in_url: '/listings/sold/',
      rows: [],
    }), { 'WWW-Authenticate': 'Bearer' });
  }
  if (!rateOk(who.id)) return reply(429, JSON.stringify({ error: 'rate_limited', rows: [] }), { 'Retry-After': '600' });
  let body = readBundled(rel);
  if (body == null) return reply(404, JSON.stringify({ error: 'not_found', rows: [] }));
  if (rel.startsWith('agent-sales/')) body = windowAgentSales(body);
  return reply(200, body);
};
